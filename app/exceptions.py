"""
Deterministic, rule-based exception classification for each SettlementBatch.
Must run after matching.py (needs SettlementBatch.bank_transaction_id / Match rows)
and reads bridge.py's numbers. Every comparison and the suggested_action text below
is fixed Python logic -- nothing here is generated by an LLM.

requires_approval and blocks_reconciliation are not columns on ExceptionRecord --
they're fully determined by classification alone (see CLASSIFICATION_INFO), so they're
derived on demand rather than duplicated into the database.
"""
import datetime
import json
from dataclasses import dataclass
from typing import List, Optional

from sqlalchemy.orm import Session

from app import models, bridge
from app.money import paise_to_rupees

# Set to exact equality (0) rather than a nonzero tolerance -- we have no real
# settlement data exhibiting genuine paisa-level aggregation rounding drift to
# calibrate a production tolerance against. A real deployment processing actual
# multi-line-item settlements might need a small empirically-calibrated tolerance;
# we're not guessing one here without data, same principle as disabling unverified
# refund-rate anomaly detection.
TOLERANCE = 0

